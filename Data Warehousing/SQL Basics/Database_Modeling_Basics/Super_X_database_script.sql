
CREATE TABLE teams (
    name text NOT NULL UNIQUE
);
CREATE TABLE car_models(
    model_name text PRIMARY KEY
);
CREATE TABLE cars(
    car_id SERIAL PRIMARY KEY,
    model_name text references car_models(model_name) NOT NULL
);
CREATE TABLE players(
    player_name text PRIMARY KEY,
    first_name text,
    last_name text,
    team text references teams(name) NOT NULL,
);

CREATE TABLE races(
    start_time TIMESTAMP,
    end_time TIMESTAMP,
    race_name TEXT PRIMARY KEY
);
DROP TABLE runs;
CREATE TABLE runs(
    id SERIAL PRIMARY KEY,
    player_name text references players(player_name) NOT NULL,
    "time(ss)" REAL NOT NULL,
    race_name TEXT references races(race_name) NOT NULL,
    car_used INTEGER references cars(car_id) NOT NULL,
    UNIQUE(race_name, player_name)
    );

CREATE TABLE point_guide(
rank INT,
points INT
);
