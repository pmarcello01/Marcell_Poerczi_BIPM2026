-- QUERIES
DROP TABLE results_master;
CREATE TABLE results_master AS
SELECT
    race_name,
    DATE(races.start_time),
    runs.player_name,
    name,
    model_name,
    first_name,
    last_name,
    runs."time(ss)",
    RANK() OVER (
        PARTITION BY race_name
        ORDER BY runs."time(ss)" ASC
    ) AS rank
FROM races
INNER JOIN runs USING (race_name)
LEFT JOIN cars ON runs.car_used = cars.car_id
LEFT JOIN car_models USING (model_name)
LEFT JOIN players USING (player_name)
LEFT JOIN teams ON teams.name = players.team
WHERE race_name IN (
    SELECT race_name
    FROM runs
    GROUP BY race_name
    HAVING COUNT(DISTINCT player_name) >= 2
)
-- a race is displayed only if there are at least two players;

--INDIVIDUAL LEADERBOARD
DROP TABLE individual_leaderboard;
CREATE VIEW individual_leaderboard AS
SELECT players.player_name, sum(points)
FROM players 
    LEFT JOIN results_master USING (player_name)
    LEFT JOIN point_guide USING (rank)
GROUP BY players.player_name;

--TEAM LEADERBOARD
DROP TABLE team_leaderboard;
CREATE VIEW team_leaderboard AS
SELECT teams.name, SUM(points)
FROM teams
    LEFT JOIN results_master USING (name)
    LEFT JOIN point_guide USING (rank)
GROUP BY teams.name
HAVING teams.name IN(
    SELECT team
    FROM players
);

